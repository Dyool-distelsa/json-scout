// @vitest-environment jsdom
import html from '../index.html?raw';
import { expect, it, vi } from 'vitest';
import { EditorView } from '@codemirror/view';

it('splits real editors and routes tools, movement, close and Diff', async () => {
  document.documentElement.innerHTML = html;
  localStorage.clear();
  vi.stubGlobal('matchMedia', () => ({ matches: false, addEventListener() {} }));
  vi.stubGlobal('ResizeObserver', class { observe() {} disconnect() {} });
  Range.prototype.getClientRects = () => [];
  Range.prototype.getBoundingClientRect = () => ({ left: 0, right: 0, top: 0, bottom: 0 });
  const createURL = vi.fn(() => 'blob:test');
  vi.stubGlobal('URL', Object.assign(URL, { createObjectURL: createURL, revokeObjectURL: vi.fn() }));
  vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(() => {});
  await import('../main.js');
  const left = () => EditorView.findFromDOM(document.querySelector('#editor .cm-editor'));
  const right = () => EditorView.findFromDOM(document.querySelector('#editor-split .cm-editor'));
  left().dispatch({ changes: { from: 0, insert: '{"left":1}' } });
  document.querySelector('[aria-label="Split editor"]').click();
  expect(document.querySelector('#split-group').hidden).toBe(false);
  right().dispatch({ changes: { from: 0, to: right().state.doc.length, insert: '{"right":2}' } });
  document.querySelector('#editor-split').dispatchEvent(new Event('focusin', { bubbles: true }));
  document.querySelector('[data-action="format"]').click();
  expect(right().state.doc.toString()).toContain('\n');
  expect(left().state.doc.toString()).toBe('');
  [...document.querySelectorAll('#menu-file [role=menuitem]')].find(b => b.textContent.startsWith('Save') && !b.textContent.startsWith('Save As')).click();
  expect(createURL).toHaveBeenCalled();
  expect(createURL.mock.calls[0][0].size).toBe(right().state.doc.length);
  const source = document.querySelector('#doc-tabs-split [role=tab]');
  const target = document.querySelector('#doc-tabs [role=tab]');
  document.elementFromPoint = vi.fn(() => target);
  source.dispatchEvent(new MouseEvent('pointerdown', { bubbles: true, button: 0, clientX: 1, clientY: 1 }));
  document.dispatchEvent(new MouseEvent('pointermove', { bubbles: true, clientX: 30, clientY: 1, cancelable: true }));
  expect(document.querySelector('#doc-tabs').classList.contains('doc-tabs--drop')).toBe(true);
  document.dispatchEvent(new MouseEvent('pointerup', { bubbles: true, clientX: 30, clientY: 1 }));
  expect(document.querySelector('#split-group').hidden).toBe(true);
  expect(document.querySelectorAll('#doc-tabs [role=tab]')).toHaveLength(2);
  expect(left().state.doc.toString()).toContain('right');
  document.querySelector('[aria-label="Split editor"]').click();
  document.querySelector('#doc-tabs-split [role=tab] .doc-tab__close').click();
  const modalButton = (label) => [...document.querySelectorAll('[role=dialog] button')].find(b => b.textContent === label);
  modalButton('Cancel').click();
  await Promise.resolve();
  expect(document.querySelector('#split-group').hidden).toBe(false);
  document.querySelector('#doc-tabs-split [role=tab] .doc-tab__close').click();
  modalButton("Don't save").click();
  await Promise.resolve(); await Promise.resolve();
  expect(document.querySelector('#split-group').hidden).toBe(true);
  document.querySelector('#doc-tabs [aria-label="New document"]').click();
  document.querySelector('[aria-label="Split editor"]').click();
  document.querySelector('[data-action="diffToggle"]').click();
  document.querySelector('.compare-menu [role=menuitem]').click();
  expect(document.querySelector('#split-group').hidden).toBe(true);
  expect(document.querySelector('#diff-secondary-container').hidden).toBe(false);
  document.querySelector('#compare-close').click();
  expect(document.querySelector('#diff-secondary-container').hidden).toBe(true);
  vi.restoreAllMocks(); vi.unstubAllGlobals();
}, 15000);
